begin;

-- Preserve existing placeholder rows and IDs.
create table if not exists public.tickers (id bigint generated by default as identity primary key);
alter table public.tickers
  add column if not exists ticker text,
  add column if not exists cik bigint,
  add column if not exists name text,
  add column if not exists edgar_snapshot jsonb,
  add column if not exists edgar_fetched_at timestamptz,
  add column if not exists prices_fetched_at timestamptz;
create unique index if not exists stock_tickers_symbol_key on public.tickers (ticker);

create table if not exists public.price_history (
  ticker text not null references public.tickers(ticker),
  date date not null,
  close double precision not null check (close > 0),
  adjusted_close double precision,
  primary key (ticker, date)
);
alter table public.price_history add column if not exists adjusted_close double precision;

create table if not exists public.fundamentals_quarterly (id bigint generated by default as identity primary key);
alter table public.fundamentals_quarterly
  add column if not exists ticker text references public.tickers(ticker),
  add column if not exists quarter date,
  add column if not exists revenue double precision,
  add column if not exists operating_income double precision,
  add column if not exists diluted_eps double precision,
  add column if not exists free_cash_flow double precision,
  add column if not exists tax double precision,
  add column if not exists pretax double precision,
  add column if not exists debt double precision,
  add column if not exists cash double precision,
  add column if not exists shares double precision;
create unique index if not exists stock_fundamentals_period_key on public.fundamentals_quarterly (ticker, quarter);

create table if not exists public.valuation_history (id bigint generated by default as identity primary key);
alter table public.valuation_history
  add column if not exists ticker text references public.tickers(ticker),
  add column if not exists quarter date,
  add column if not exists close double precision,
  add column if not exists ev double precision,
  add column if not exists nopat double precision,
  add column if not exists ev_nopat double precision;
create unique index if not exists stock_valuation_period_key on public.valuation_history (ticker, quarter);

alter table public.tickers enable row level security;
alter table public.price_history enable row level security;
alter table public.fundamentals_quarterly enable row level security;
alter table public.valuation_history enable row level security;
revoke all on public.tickers, public.price_history, public.fundamentals_quarterly, public.valuation_history from anon, authenticated;
grant select, insert, update on public.tickers, public.price_history, public.fundamentals_quarterly, public.valuation_history to service_role;
do $$
declare
  target text;
  seq text;
begin
  foreach target in array array['tickers', 'fundamentals_quarterly', 'valuation_history'] loop
    seq := pg_get_serial_sequence('public.' || target, 'id');
    if seq is not null then
      execute format('grant usage on sequence %s to service_role', seq);
    end if;
  end loop;
end $$;
notify pgrst, 'reload schema';
commit;
