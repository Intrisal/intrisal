import { readFile, readdir, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";

const directory = process.argv[2] ?? ".cache/edgar-backfill";
const files = (await readdir(directory)).sort();
const reports = files.filter((file) => /^tsm-\d{4}-\d{2}-\d{2}\.html$/.test(file));

function clean(html) {
  return html.replace(/<[^>]*>/g, " ").replace(/&nbsp;|&#160;|&#12288;/gi, " ").replace(/\s+/g, " ").trim();
}

function readRows(html, tableLimit = 25) {
  return [...html.matchAll(/<table\b[^>]*>([\s\S]*?)<\/table>/gi)].slice(0, tableLimit).flatMap((table) =>
    [...table[1].matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)].map((row) =>
      [...row[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)].map((cell) => clean(cell[1])).filter(Boolean)));
}

function numbers(row) {
  return row.slice(1).flatMap((cell) => {
    if (cell === "-") return [0];
    const value = cell.replace(/[\s,$)]/g, "").replace(/^\(/, "-");
    return /^-?\d+(?:\.\d+)?$/.test(value) ? [Number(value)] : [];
  });
}

function readMetric(rows, label) {
  const row = rows.find((entry) => label.test(entry[0]));
  return row ? numbers(row)[0] : undefined;
}

function parseStatement(html, date) {
  assert.match(clean(html.slice(0, 2_000_000)), /in thousands of new taiwan dollars/i, date);
  const rows = readRows(html);
  const capexRow = rows.find((row) => /^property, plant and equipment$/i.test(row[0]) && numbers(row)[0] < 0);
  const amount = {
    revenue: readMetric(rows, /^net revenue(?: \(|$)/i),
    operatingIncome: readMetric(rows, /^income from operations(?: \(|$)/i),
    pretax: readMetric(rows, /^income before income tax$/i),
    tax: readMetric(rows, /^income tax expense(?: \(|$)/i),
    earnings: readMetric(rows, /^diluted earnings per share$/i),
    cfo: readMetric(rows, /^net cash (?:generated by|provided by) operating activities$/i),
    capex: capexRow ? Math.abs(numbers(capexRow)[0]) : undefined,
    cash: readMetric(rows, /^cash and cash equivalents(?: \(|$)/i),
  };
  for (const [metric, value] of Object.entries(amount)) assert.ok(Number.isFinite(value), date + " " + metric);
  assert.ok(amount.revenue > 0 && amount.operatingIncome < amount.revenue && amount.earnings > 0 && amount.earnings < 200, date);
  return amount;
}

const quarterEps = JSON.parse(await readFile(directory + "/tsm-fourth-quarter-eps.json", "utf8"));
const statements = new Map();
for (const file of reports) {
  const date = file.slice(4, 14);
  statements.set(date, parseStatement(await readFile(directory + "/" + file, "utf8"), date));
}

const metrics = Object.fromEntries(["revenue", "operatingIncome", "dilutedEps", "freeCashFlow", "pretax", "tax"]
  .map((name) => [name, { ends: [], values: [] }]));
const balances = {};
const billions = (value) => value / 1_000_000;
function addPoint(metric, date, value) {
  if (!Number.isFinite(value)) return;
  metrics[metric].ends.push(date);
  metrics[metric].values.push(value);
}

const releasePeriods = { first: "03-31", second: "06-30", third: "09-30", fourth: "12-31" };
for (const file of files.filter((name) => name.startsWith("tsm-release-"))) {
  const html = await readFile(directory + "/" + file, "utf8");
  const text = clean(html);
  const label = text.match(/TSMC Reports (First|Second|Third|Fourth) Quarter EPS of NT\$\s*([\d.]+)/i);
  if (!label) continue;
  const quarter = releasePeriods[label[1].toLowerCase()];
  const fileYear = Number(file.slice(12, 16));
  const date = `${quarter === "12-31" ? fileYear - 1 : fileYear}-${quarter}`;
  // Exclude quarters prior to the July 2011 stock dividend from this share-basis series.
  if (date < "2011-09-30" || statements.has(date) || metrics.revenue.ends.includes(date)) continue;
  const rows = readRows(html);
  const revenue = readMetric(rows, /^net sales$/i);
  const operating = readMetric(rows, /^income from operations$/i);
  const pretax = readMetric(rows, /^income before tax$/i);
  assert.ok(revenue > operating && operating > 0 && pretax > 0, date + " release");
  addPoint("revenue", date, revenue / 1_000);
  addPoint("operatingIncome", date, operating / 1_000);
  addPoint("pretax", date, pretax / 1_000);
  // Only the GAAP release headline's NT$ per ordinary share belongs in the chart.
  const explicitDiluted = text.match(/diluted (?:earnings per share|EPS) (?:of|was) NT\$\s*([\d.]+)/i);
  if (explicitDiluted) {
    assert.equal(Number(explicitDiluted[1].replace(/\.$/, "")), Number(label[2].replace(/\.$/, "")), date + " EPS");
    addPoint("dilutedEps", date, Number(label[2].replace(/\.$/, "")));
  }
}

const historicalCash = new Map();
for (const file of files.filter((name) => name.startsWith("tsm-statements-"))) {
  const html = await readFile(directory + "/" + file, "utf8");
  const cashHeading = html.search(/consolidated.{0,70}statements of cash flows/i);
  const cashTable = cashHeading > 0 ? html.toLowerCase().lastIndexOf("<table", cashHeading) : -1;
  const cashStatement = cashTable >= 0 ? html.slice(cashTable) : html;
  const preview = clean(cashStatement.slice(0, 2_000_000));
  const consolidated = preview.search(/consolidated statements of cash flows/i);
  const parent = preview.search(/parent company only statements of cash flows/i);
  if (consolidated < 0 || (parent >= 0 && parent < consolidated) || !/in thousands of new taiwan dollars/i.test(preview)) continue;
  const year = Number(file.slice(15, 19));
  const month = file.slice(20, 22);
  const period = { "02": "12-31", "03": "12-31", "05": "03-31", "08": "06-30", "09": "06-30", "11": "09-30" }[month];
  if (!period) continue;
  const date = `${period === "12-31" ? year - 1 : year}-${period}`;
  const [periodMonth, periodDay] = period.split("-").map(Number);
  const periodName = new Intl.DateTimeFormat("en-US", { month: "long", timeZone: "UTC" })
    .format(new Date(Date.UTC(year, periodMonth - 1, periodDay)));
  if (!new RegExp(`${periodName} ${periodDay},? (?:${date.slice(0, 4)})`, "i").test(preview)) continue;
  const rows = readRows(cashStatement, 60);
  const cfoIndex = rows.findIndex((row) => /^net cash (?:generated by|provided by) operating activities$/i.test(row[0]));
  if (cfoIndex < 0) continue;
  const cfo = numbers(rows[cfoIndex])[0];
  const capexRow = rows.slice(cfoIndex + 1).find((row) => /^property, plant and equipment$/i.test(row[0]) && numbers(row)[0] < 0);
  if (!capexRow || !Number.isFinite(cfo)) continue;
  const cumulative = cfo + numbers(capexRow)[0];
  if (historicalCash.has(date)) assert.equal(historicalCash.get(date), cumulative, date + " cash statement");
  historicalCash.set(date, cumulative);
}
for (const [date, total] of [...historicalCash].sort(([a], [b]) => a.localeCompare(b))) {
  if (date < "2011-09-30" || statements.has(date)) continue;
  const priorEnd = { "06-30": "03-31", "09-30": "06-30", "12-31": "09-30" }[date.slice(5)];
  const prior = priorEnd && historicalCash.get(date.slice(0, 5) + priorEnd);
  if (!priorEnd || prior !== undefined) addPoint("freeCashFlow", date, billions(total - (prior || 0)));
}

for (const [date, statement] of statements) {
  const year = date.slice(0, 4);
  const priorEnd = { "06-30": "03-31", "09-30": "06-30", "12-31": "09-30" }[date.slice(5)];
  const prior = priorEnd && statements.get(year + "-" + priorEnd);
  const annual = date.endsWith("12-31");
  const values = {
    dilutedEps: annual ? quarterEps[date] : statement.earnings,
    freeCashFlow: !priorEnd || prior
      ? billions(statement.cfo - statement.capex - (prior ? prior.cfo - prior.capex : 0)) : undefined,
  };
  for (const field of ["revenue", "operatingIncome", "pretax", "tax"]) {
    const current = annual
      ? ["03-31", "06-30", "09-30"].map((end) => statements.get(year + "-" + end)) : [];
    if (current.some((quarter) => !quarter)) continue;
    values[field] = billions(statement[field] - current.reduce((total, quarter) => total + quarter[field], 0));
  }
  for (const [metric, value] of Object.entries(values)) addPoint(metric, date, value);
  balances[date] = { cash: billions(statement.cash), debt: null, shares: null };
}

const lastReportEnd = [...statements.keys()].at(-1);
assert.equal(lastReportEnd, "2026-09-30");
assert.equal(metrics.revenue.values.at(-1), 1494.243284);
assert.equal(metrics.operatingIncome.values.at(-1), 876.445164);
assert.equal(metrics.dilutedEps.values.at(-1), 29.43);
assert.equal(metrics.freeCashFlow.values.at(-1), 476.569452);
